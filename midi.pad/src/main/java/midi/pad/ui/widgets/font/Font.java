	public static int[] getBitmap(final String str, final int offs) {
		final int map[] = new int[8];
		final int pos = offs / 6;
		final int bit = offs % 6;
		if (str != null && pos < str.length() && pos >= 0) {
			final int curChar = str.charAt(pos) % 128;
			final int nextChar;
			if (pos + 1 < str.length()) {
				nextChar = str.charAt(pos + 1) % 128;
			} else {
				nextChar = ' ';
			}
			for (int i = 0; i < map.length; i++) {
				map[i] = 0xff & (font6x8_basic[curChar][i] >> bit
						| font6x8_basic[nextChar][i] << (6 - bit));
			}
		}
		return map;
	}
